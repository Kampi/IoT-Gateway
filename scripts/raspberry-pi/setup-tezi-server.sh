# Sets up a Raspberry Pi as network feed server for the Toradex Easy Installer
# (and as RAUC bundle server for OTA updates), see
# os/layers/meta-iot-gateway-os/docs/tezi-feed-raspberry-pi.md:
#
#   1. NetworkManager connection on the Ethernet port (Easy Installer network
#      + static network of the flashed gateway on Dahlia, no default route)
#   2. dnsmasq: DHCP + DNS on that port only, answers tezi.toradex.com with
#      the Pi so the Easy Installer lists the local images without setup
#   3. nginx: serves the web root (image_list.json, images, bundles/)
#   4. avahi: _tezi._tcp announcement (optional)
#   5. uuu >= 1.5.165 for USB recovery, built from source (optional)
#
# Tested on Raspberry Pi OS / Debian 12 bookworm with NetworkManager. Can be
# run again at any time: existing settings are updated, not duplicated.
#
# Usage:
#   sudo ./setup-tezi-server.sh [--with-uuu] [--no-avahi]
#
# Settings (environment variables):
#   ETH_IFACE      Ethernet port to the gateway          (default: eth0)
#   TEZI_ADDRESS   Pi address in the Easy Installer net  (default: 192.168.10.1/24)
#   GATEWAY_ADDRESS Pi address towards the flashed gateway (default: 192.168.0.1/24)
#   DHCP_RANGE     DHCP range for the Easy Installer     (default: 192.168.10.50,192.168.10.150,12h)
#   WEB_ROOT       directory served by nginx             (default: /var/www/html)
#   WEB_OWNER      user that uploads images / bundles    (default: the user calling sudo)
#   CON_NAME       NetworkManager connection name        (default: Local)
#   UUU_SRC        source directory for the uuu build    (default: /usr/local/src/mfgtools)
set -euo pipefail

ETH_IFACE=${ETH_IFACE:-eth0}
TEZI_ADDRESS=${TEZI_ADDRESS:-192.168.10.1/24}
GATEWAY_ADDRESS=${GATEWAY_ADDRESS:-192.168.0.1/24}
DHCP_RANGE=${DHCP_RANGE:-192.168.10.50,192.168.10.150,12h}
WEB_ROOT=${WEB_ROOT:-/var/www/html}
WEB_OWNER=${WEB_OWNER:-${SUDO_USER:-}}
CON_NAME=${CON_NAME:-Local}
UUU_SRC=${UUU_SRC:-/usr/local/src/mfgtools}
UUU_MIN_VERSION=1.5.165

WITH_UUU=0
WITH_AVAHI=1
for arg in "$@"; do
    case "${arg}" in
        --with-uuu) WITH_UUU=1 ;;
        --no-avahi) WITH_AVAHI=0 ;;
        -h|--help) sed -n '5,/^set -euo/p' "$0" | sed '$d; s/^# \{0,1\}//'; exit 0 ;;
        *) echo "Unknown option: ${arg} (see --help)" >&2; exit 1 ;;
    esac
done

TEZI_IP=${TEZI_ADDRESS%/*}

log() { printf '\n==> %s\n' "$*"; }
die() { echo "ERROR: $*" >&2; exit 1; }

[ "$(id -u)" -eq 0 ] || die "run with sudo"
command -v nmcli >/dev/null || die "NetworkManager (nmcli) is required"
ip link show "${ETH_IFACE}" >/dev/null 2>&1 || die "network interface ${ETH_IFACE} not found (ETH_IFACE)"

# Default route of the Pi must not be on the feed port: it is the uplink
# (Wi-Fi) the build host uses to upload images.
if ip route show default | grep -q "dev ${ETH_IFACE} "; then
    echo "WARNING: the default route is on ${ETH_IFACE}. After this script ${ETH_IFACE} has no" >&2
    echo "         default route any more: connect the Pi to the LAN via Wi-Fi first." >&2
    read -r -p "Continue anyway? [y/N] " answer
    [ "${answer}" = "y" ] || exit 1
fi

log "Installing packages"
apt-get update -q
apt-get install -y -q dnsmasq nginx curl
[ "${WITH_AVAHI}" -eq 0 ] || apt-get install -y -q avahi-daemon

log "Network on ${ETH_IFACE}: ${TEZI_ADDRESS}, ${GATEWAY_ADDRESS} (connection '${CON_NAME}')"
if ! nmcli -t -f NAME connection show | grep -qx "${CON_NAME}"; then
    nmcli connection add type ethernet ifname "${ETH_IFACE}" con-name "${CON_NAME}" >/dev/null
fi
nmcli connection modify "${CON_NAME}" \
    connection.interface-name "${ETH_IFACE}" connection.autoconnect yes \
    ipv4.method manual ipv4.addresses "${TEZI_ADDRESS},${GATEWAY_ADDRESS}" \
    ipv4.gateway "" ipv4.never-default yes ipv6.method link-local
# Other connections on the port (e.g. "Wired connection 1" with DHCP) would
# take it over again after a reboot
nmcli -t -f NAME,DEVICE,TYPE connection show | while IFS=: read -r name dev type; do
    if [ "${type}" = "802-3-ethernet" ] && [ "${name}" != "${CON_NAME}" ] && [ "${dev}" = "${ETH_IFACE}" ]; then
        echo "Disabling autoconnect of '${name}' on ${ETH_IFACE}"
        nmcli connection modify "${name}" connection.autoconnect no
    fi
done
nmcli connection up "${CON_NAME}" >/dev/null || \
    echo "NOTE: '${CON_NAME}' not active yet (no cable on ${ETH_IFACE}?), it comes up with the link"

log "dnsmasq: DHCP ${DHCP_RANGE} + DNS on ${ETH_IFACE}"
cat > /etc/dnsmasq.d/tezi.conf <<EOF
# Generated by setup-tezi-server.sh - DHCP + DNS for the Toradex Easy
# Installer on ${ETH_IFACE} only
interface=${ETH_IFACE}
# also starts while ${ETH_IFACE} has no address yet (boot), only binds ${ETH_IFACE}
bind-dynamic
dhcp-range=${DHCP_RANGE}
# no default route for the clients, the feed is local
dhcp-option=option:router
dhcp-authoritative
log-dhcp
# The Easy Installer always asks its default feed tezi.toradex.com for
# image_list.json: answer with this Pi, then it lists the local images
# without any configuration on the device.
address=/tezi.toradex.com/${TEZI_IP}
EOF
dnsmasq --test
systemctl enable dnsmasq >/dev/null 2>&1
systemctl restart dnsmasq

log "nginx: web root ${WEB_ROOT}"
mkdir -p "${WEB_ROOT}/bundles"
if [ ! -f "${WEB_ROOT}/image_list.json" ]; then
    cat > "${WEB_ROOT}/image_list.json" <<'EOF'
{
    "config_format": 1,
    "images": []
}
EOF
    echo "Created an empty ${WEB_ROOT}/image_list.json"
fi
if [ -n "${WEB_OWNER}" ] && [ "${WEB_OWNER}" != "root" ]; then
    chown "${WEB_OWNER}:" "${WEB_ROOT}" "${WEB_ROOT}/bundles" "${WEB_ROOT}/image_list.json"
    echo "${WEB_ROOT} belongs to ${WEB_OWNER} (uploads via scp without sudo)"
fi
systemctl enable nginx >/dev/null 2>&1
systemctl restart nginx

if [ "${WITH_AVAHI}" -eq 1 ]; then
    log "avahi: _tezi._tcp announcement"
    mkdir -p /etc/avahi/services
    cat > /etc/avahi/services/tezi.service <<'EOF'
<?xml version="1.0" standalone="no"?>
<!DOCTYPE service-group SYSTEM "avahi-service.dtd">
<service-group>
  <name>GatewayOS Easy Installer feed (%h)</name>
  <service>
    <type>_tezi._tcp</type>
    <port>80</port>
    <txt-record>path=/image_list.json</txt-record>
  </service>
</service-group>
EOF
    systemctl restart avahi-daemon
fi

if [ "${WITH_UUU}" -eq 1 ]; then
    log "uuu >= ${UUU_MIN_VERSION} for USB recovery"
    current=$(uuu -h 2>/dev/null | sed -n 's/.*libuuu_\([0-9.]*\).*/\1/p' | sed -n 1p || true)
    if [ -n "${current}" ] && [ "$(printf '%s\n%s\n' "${UUU_MIN_VERSION}" "${current}" | sort -V | sed -n 1p)" = "${UUU_MIN_VERSION}" ]; then
        echo "uuu ${current} is new enough"
    else
        # Debian bookworm ships 1.4.193: loads the first stage of the Easy
        # Installer 7.x, then times out (SDPV: write ... LIBUSB_ERROR_TIMEOUT)
        apt-get install -y -q git cmake g++ pkg-config libusb-1.0-0-dev libbz2-dev \
            libzstd-dev libssl-dev zlib1g-dev libtinyxml2-dev
        if [ -d "${UUU_SRC}/.git" ]; then
            git -C "${UUU_SRC}" pull -q --ff-only
        else
            git clone -q https://github.com/nxp-imx/mfgtools.git "${UUU_SRC}"
        fi
        cmake -S "${UUU_SRC}" -B "${UUU_SRC}/build" -DCMAKE_BUILD_TYPE=Release >/dev/null
        cmake --build "${UUU_SRC}/build" -j"$(nproc)"
        install -m 0755 "${UUU_SRC}/build/uuu/uuu" /usr/local/bin/uuu
        echo "Installed $(/usr/local/bin/uuu -h 2>/dev/null | sed -n 1p) to /usr/local/bin/uuu"
    fi
fi

log "Checks"
ok=1
if curl -fsS -o /dev/null "http://127.0.0.1/image_list.json"; then
    echo "OK   nginx serves /image_list.json"
else
    echo "FAIL nginx does not serve /image_list.json"; ok=0
fi
if ss -ulnp 2>/dev/null | grep -q "dnsmasq"; then
    echo "OK   dnsmasq is running"
else
    echo "FAIL dnsmasq is not running (journalctl -u dnsmasq)"; ok=0
fi
if ip -4 addr show "${ETH_IFACE}" | grep -q "inet ${TEZI_IP}/"; then
    echo "OK   ${ETH_IFACE} has ${TEZI_IP}"
else
    echo "NOTE ${ETH_IFACE} has no ${TEZI_IP} yet (no link?), dnsmasq binds it when it comes up"
fi

cat <<EOF

Done. Next steps (build host, see docs/tezi-feed-raspberry-pi.md):
  Easy Installer image:
    scp os/build/deploy/images/verdin-imx8mm/<image>-Tezi_<version>.tar <user>@<pi>:/tmp/
    ssh <user>@<pi> "tar -xf /tmp/<image>-Tezi_<version>.tar -C ${WEB_ROOT}"
    then add "<image folder>/image.json" to ${WEB_ROOT}/image_list.json
  RAUC bundle for OTA updates (GATEWAY_UPDATE_SERVER = "http://${GATEWAY_ADDRESS%/*}"):
    scp os/build/deploy/images/verdin-imx8mm/gateway-os-bundle-verdin-imx8mm.raucb <user>@<pi>:${WEB_ROOT}/bundles/
EOF
[ "${ok}" -eq 1 ] || exit 1
